#!/usr/bin/env node
/**
 * Per-route first-load JS budget checker.
 *
 * Reads the build manifests Next.js writes under .next/ and computes, for every
 * app route, the bytes a browser downloads before that route is interactive:
 * the route's own chunks plus the shared chunks every route pays for.
 * Compares each against docs/perf/budgets.json and exits nonzero on a breach,
 * naming every route that broke and by how much.
 *
 * Sizes are GZIPPED, which is what actually crosses the wire and what Next's
 * own build table reports. Measuring raw disk bytes instead overstates
 * everything by roughly 3x and makes these numbers incomparable to the build
 * output. Figures here land within a few kB of Next's "First Load JS" column.
 *
 * Why manifests rather than parsing build stdout: stdout rounds to 0.1 kB and
 * reformats between Next versions, so a budget built on it drifts. The
 * manifests are the same data the framework uses to emit <script> tags.
 *
 *   node scripts/check-route-budgets.mjs            # check against budgets
 *   node scripts/check-route-budgets.mjs --json     # machine-readable report
 *   node scripts/check-route-budgets.mjs --write    # seed/refresh budgets.json
 *
 * --write records CURRENT sizes plus headroom. Only run it deliberately: it is
 * how a regression gets blessed into the baseline by accident.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const NEXT_DIR = join(ROOT, '.next');
const BUDGETS = join(ROOT, 'docs/perf/budgets.json');

const args = process.argv.slice(2);
const asJson = args.includes('--json');
const write = args.includes('--write');
/* Headroom applied by --write. 10% absorbs ordinary churn without letting a
   real regression through unnoticed. */
const HEADROOM = 1.1;

function read(path) {
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch {
    return null;
  }
}

function fail(msg) {
  console.error(`\n  ${msg}\n`);
  process.exit(1);
}

const appManifest = read(join(NEXT_DIR, 'app-build-manifest.json'));
const buildManifest = read(join(NEXT_DIR, 'build-manifest.json'));
if (!appManifest || !buildManifest) {
  fail('No build manifests found. Run `npm run build` first.');
}

/* Every route pays for the shared runtime regardless of its own imports. */
const shared = new Set([
  ...(buildManifest.rootMainFiles || []),
  ...(buildManifest.polyfillFiles || []),
]);

/* Gzip each chunk once and cache by path: a chunk shared by 80 routes is
   compressed a single time. */
const sizeCache = new Map();
function bytes(file) {
  if (sizeCache.has(file)) return sizeCache.get(file);
  let n = 0;
  try {
    n = gzipSync(readFileSync(join(NEXT_DIR, file))).length;
  } catch {
    /* A referenced chunk that is not on disk contributes nothing rather than
       crashing the check: a partial build should report, not explode. */
  }
  sizeCache.set(file, n);
  return n;
}

const routes = {};
for (const [route, files] of Object.entries(appManifest.pages || {})) {
  const all = new Set([...files, ...shared]);
  let total = 0;
  for (const f of all) if (f.endsWith('.js')) total += bytes(f);
  routes[route] = total;
}

const sharedBytes = [...shared].filter((f) => f.endsWith('.js')).reduce((a, f) => a + bytes(f), 0);
const kb = (n) => Math.round((n / 1024) * 10) / 10;

if (write) {
  const budgets = {
    _comment:
      "Per-route first-load JS budgets in KB, GZIPPED (same basis as Next's build table). Generated by " +
      'scripts/check-route-budgets.mjs --write from a real build, plus headroom. ' +
      'Tighten deliberately; do not regenerate to silence a regression.',
    _generatedAt: new Date().toISOString(),
    _headroom: HEADROOM,
    _sharedKb: kb(sharedBytes),
    routes: Object.fromEntries(
      Object.entries(routes)
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([r, n]) => [r, Math.ceil(kb(n) * HEADROOM)]),
    ),
  };
  writeFileSync(BUDGETS, `${JSON.stringify(budgets, null, 2)}\n`);
  console.log(`Wrote ${Object.keys(routes).length} route budgets to docs/perf/budgets.json`);
  console.log(`Shared chunks: ${kb(sharedBytes)} kB`);
  process.exit(0);
}

const budgets = read(BUDGETS);
if (!budgets) {
  fail(
    'docs/perf/budgets.json missing. Seed it with: node scripts/check-route-budgets.mjs --write',
  );
}

const breaches = [];
const unbudgeted = [];
for (const [route, n] of Object.entries(routes)) {
  const budget = budgets.routes?.[route];
  if (budget == null) {
    unbudgeted.push(route);
    continue;
  }
  const actual = kb(n);
  if (actual > budget)
    breaches.push({ route, actual, budget, over: Math.round((actual - budget) * 10) / 10 });
}

if (asJson) {
  console.log(JSON.stringify({ sharedKb: kb(sharedBytes), routes, breaches, unbudgeted }, null, 2));
  process.exit(breaches.length ? 1 : 0);
}

const top = Object.entries(routes)
  .sort(([, a], [, b]) => b - a)
  .slice(0, 10);

console.log(`\n  Shared chunks: ${kb(sharedBytes)} kB gzipped (paid by every route)\n`);
console.log('  Heaviest routes by first-load JS (gzipped):');
for (const [route, n] of top) console.log(`    ${String(kb(n)).padStart(8)} kB  ${route}`);

if (unbudgeted.length) {
  console.log(`\n  ${unbudgeted.length} route(s) have no budget yet:`);
  for (const r of unbudgeted.slice(0, 10)) console.log(`    ${r}`);
  if (unbudgeted.length > 10) console.log(`    ... and ${unbudgeted.length - 10} more`);
}

if (breaches.length) {
  console.error(`\n  ${breaches.length} route(s) over budget:\n`);
  for (const b of breaches.sort((x, y) => y.over - x.over)) {
    console.error(`    ${b.route}\n      ${b.actual} kB vs ${b.budget} kB budget (+${b.over} kB)`);
  }
  console.error(
    '\n  Reduce the route, or raise its budget deliberately in docs/perf/budgets.json.\n',
  );
  process.exit(1);
}

console.log(`\n  All ${Object.keys(routes).length} budgeted routes within budget.\n`);
