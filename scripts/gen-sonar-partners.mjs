// Regenerates src/lib/sonar/analysts/partners.js from the "Support when:" line of every
// sonar-skills/<skill>/SKILL.md. Run after editing a skill's collaboration section:
//   node --no-warnings --import ./scripts/register-sonar-loader.mjs scripts/gen-sonar-partners.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

export async function derivePartners() {
  const { ANALYSTS } = await import('@/lib/sonar/analysts/registry');
  const ids = Object.keys(ANALYSTS);
  const partners = {};
  for (const dir of readdirSync('sonar-skills').sort()) {
    let md;
    try {
      md = readFileSync(`sonar-skills/${dir}/SKILL.md`, 'utf8');
    } catch {
      continue;
    }
    const sup = (md.match(/^analyst:\s*(\S+)/m) || [])[1];
    const line = (md.match(/^- Support when:(.*)$/m) || [])[1] || '';
    if (!sup) continue;
    for (const seg of line.split(';')) {
      for (const lead of ids) {
        if (lead === sup) continue;
        if (new RegExp(`\\b${lead.replace('-', '[- ]')}\\b`, 'i').test(seg)) {
          partners[lead] ||= [];
          if (!partners[lead].includes(sup)) partners[lead].push(sup);
        }
      }
    }
  }
  return Object.fromEntries(
    Object.keys(partners)
      .sort()
      .map((k) => [k, partners[k].sort()]),
  );
}

if (process.argv[1]?.endsWith('gen-sonar-partners.mjs')) {
  const p = await derivePartners();
  const body = `/**
 * Sonar 6.2 (Nov 28 2026): which specialists support which lead, derived from the
 * "Support when:" line of each sonar-skills/<skill>/SKILL.md (GENERATED by
 * scripts/gen-sonar-partners.mjs; do not edit by hand; check-sonar-analyst-evals.mjs fails
 * when it drifts from the skills). { [lead]: [supporting analysts] }.
 */
export const PARTNERS = ${JSON.stringify(p, null, 2)};
`;
  writeFileSync('src/lib/sonar/analysts/partners.js', body);
  console.log('wrote partners for', Object.keys(p).length, 'leads');
}
