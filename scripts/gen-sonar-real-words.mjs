/**
 * Regenerates src/lib/sonar/understand/real-words.js: the real English words
 * the Sonar spell pass must leave as typed.
 *
 *   npm i --no-save an-array-of-english-words@2
 *   node --import ./scripts/register-sonar-loader.mjs scripts/gen-sonar-real-words.mjs
 *
 * Run it after changing LEXICON, STOPWORDS or the correction rules in
 * understand/spell.js. A word is listed when correct() would rewrite it into a
 * different lexicon term; plural and singular pairs of a lexicon term
 * ("aerospaces" -> "aerospace") are left out, because normalising those is
 * the point of the pass, and so are words the pass reads as a place
 * ("argentine" -> argentina), which is how the country resolves. The guard is cleared first so every word is tested
 * against the bare rules.
 */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const words = require('an-array-of-english-words');
const { REAL_WORDS } = await import(path.join(root, 'src/lib/sonar/understand/real-words.js'));
REAL_WORDS.clear();
const { correct } = await import(path.join(root, 'src/lib/sonar/understand/spell.js'));
const { GEO_LEXICON } = await import(path.join(root, 'src/lib/sonar/understand/lexicons.js'));

const out = [];
for (const w of words) {
  if (w.length < 4 || !/^[a-z]+$/.test(w)) continue;
  const r = correct([w]);
  if (!r.corrections.length) continue;
  const t = r.corrections[0].to.toLowerCase();
  const inflection = w === `${t}s` || t === `${w}s` || w === `${t}es` || t === `${w}es`;
  /* A word read as a place ("argentine" -> argentina) keeps resolving to it:
     that rewrite is how the country is found, not a false typo. */
  if (!inflection && !GEO_LEXICON.has(t)) out.push(w);
}
out.sort();

const lines = [];
let cur = '';
for (const x of out) {
  if (`${cur} ${x}`.length > 96) {
    lines.push(cur.trim());
    cur = '';
  }
  cur += ` ${x}`;
}
if (cur.trim()) lines.push(cur.trim());

const body = `/**
 * GENERATED by scripts/gen-sonar-real-words.mjs. Do not edit by hand.
 *
 * Real English words that the Sonar spell pass (understand/spell.js) would
 * otherwise rewrite into a different finance term: every dictionary word of
 * 4+ letters, not already in the lexicon or the stopwords, that correct()
 * turned into another word (${out.length} words). Plural and singular pairs of a
 * lexicon term, and words read as a place name, are not listed, so those
 * still normalise. spell.js leaves
 * these as typed: "travel" never becomes "trades", "minerals" never becomes
 * "miners", "running" never becomes "ranking".
 *
 * Source word list: an-array-of-english-words (MIT), used at generation time
 * only; it is not a runtime dependency.
 */
const WORDS = \`
${lines.join('\n')}
\`;

export const REAL_WORDS = new Set(WORDS.split(/\\s+/).filter(Boolean));
`;
writeFileSync(path.join(root, 'src/lib/sonar/understand/real-words.js'), body);
console.log(`real-words.js: ${out.length} words`);
