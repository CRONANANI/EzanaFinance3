/**
 * Sonar adaptive research: the scenario registry (Nov 2026).
 *
 * One declarative profile per research scenario. A profile says what the
 * question is trying to find out, which evidence it must have and may use,
 * which numbers code computes for it, which analysts work it, and the order
 * its sections appear in. Profiles share the retrieval, computation and
 * rendering utilities; none of them is a pipeline of its own.
 *
 * `analysts` are ids from the existing roster (analysts/registry.js): the
 * registry is the only place a role is defined.
 *
 * `executable: true` marks a profile the adaptive orchestrator can run end to
 * end today. Every other profile still routes and plans (so the plan, its
 * evidence contract and its layout are testable), and the ping is answered by
 * the existing Sonar pipelines until its executor is built. See
 * docs/sonar/adaptive-research/README.md for what is and is not built.
 *
 * `triggers` are [RegExp, weight] pairs. The router sums the weights of every
 * trigger that matches (router.js); it never takes the first keyword hit.
 *
 * Pure data. No I/O.
 */

