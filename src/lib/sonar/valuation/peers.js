/**
 * The industry peers of `symbol`, with the logic that chose them.
 * -> { peers: string[], logic: { industry, matched: 'exact'|'contains'|null, source,
 *      excluded: string[], note } }
 */
export function industryPeers(industry, symbol, { max = 6 } = {}) {
  const sym = String(symbol || '').toUpperCase();
  const name = String(industry || '').trim();
  let list = null;
  let matched = null;
  let key = null;
  if (name && INDUSTRY_PEERS[name]) {
    list = INDUSTRY_PEERS[name];
    matched = 'exact';
    key = name;
  } else if (name) {
    const lower = name.toLowerCase();
    for (const [k, tickers] of Object.entries(INDUSTRY_PEERS)) {
      if (k.toLowerCase().includes(lower) || lower.includes(k.toLowerCase())) {
        list = tickers;
        matched = 'contains';
        key = k;
        break;
      }
    }
  }
  const all = (list || []).filter((t) => t !== sym);
  return {
    peers: all.slice(0, max),
    logic: {
      industry: name || null,
      listMatched: key,
      matched,
      source: "Ezana's curated industry peer list",
      excluded: all.slice(max),
      note: list
        ? `Companies listed under ${key}${matched === 'contains' ? ` (closest match to "${name}")` : ''}; sector-wide lists are not used.`
        : `No curated industry list for ${name || 'this company'}; no peer comparison is made rather than borrowing a sector list.`,
    },
  };
}
